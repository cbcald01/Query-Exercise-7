--CUST ID WHERE BALANCE > AVG BALANCE
--Retrieve Customer ID, Balance, and Available Credit as AVAILABLE_CREDIT (Credit Limit - Balance)
--for all customers where balance is greater than the average balance, 
--as a nested query, and Available credit is positive. Order by available credit descending.

SELECT *
	FROM CUSTOMER;

SELECT CUST_ID, FIRST_NAME, LAST_NAME, BALANCE, POSTAL, REP_ID
	FROM CUSTOMER
		WHERE BALANCE > (SELECT AVG(BALANCE) AS AVGBAL
						FROM CUSTOMER)
							ORDER BY BALANCE DESC;

SELECT *
	FROM CUSTOMER
		WHERE BALANCE > (SELECT AVG(BALANCE) AS AVGBAL
						FROM CUSTOMER)
							ORDER BY BALANCE DESC;

SELECT CUST_ID, BALANCE, CREDIT_LIMIT, (CREDIT_LIMIT - BALANCE) AS AVAILABLE_CREDIT, REP_ID
	FROM CUSTOMER
		WHERE BALANCE > (SELECT AVG(BALANCE) AS AVG_BAL
						FROM CUSTOMER)
						AND (CREDIT_LIMIT - BALANCE) >= 0
							ORDER BY AVAILABLE_CREDIT DESC;

SELECT CUST_ID, BALANCE, CREDIT_LIMIT, (CREDIT_LIMIT - BALANCE) AS AVAILABLE_CREDIT, REP_ID
	FROM CUSTOMER
		WHERE BALANCE > (SELECT AVG(BALANCE) AS AVG_BAL
						FROM CUSTOMER)
					
						OR (CREDIT_LIMIT - BALANCE) >= 500
							ORDER BY AVAILABLE_CREDIT DESC;

